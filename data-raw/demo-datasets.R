# Generates the three shipped example datasets.
#
# THIS SCRIPT REPRODUCES data/*.rda EXACTLY. Run it and the committed files are
# rewritten byte-for-byte identical, and `test-data-demo.R` checks that they
# still match what it produces. That is the whole point of a data-raw script:
# the stated origin of every shipped dataset is code this package contains.
#
# SYNTHETIC, AND rnetis'S OWN. No redistribution question attaches to any of
# them: nothing here is anyone else's data. They are also deliberately small
# and deliberately boring -- their job is to make an example runnable and a
# vignette readable, not to be interesting in themselves.
#
# WHY GENERATED RATHER THAN HAND-WRITTEN. Every one is produced by a process
# whose parameters are known, so an example that fits a model to them can
# compare the estimate against the value that generated it. A hand-typed table
# can illustrate an API; it cannot show that the API returns the right answer.
#
# Regenerate with:
#   Rscript data-raw/demo-datasets.R

library(rnetis)

# ---------------------------------------------------------------------------
# demo_influence -- one network, two waves
#
# The commonest shape in the package: a single group with one outcome row per
# actor, which is what the T <= 2 contract produces. Generated by
# simulate_influence() so the true autoregression and exposure coefficients
# are known (`gamma` and `beta` below).
# ---------------------------------------------------------------------------
sim <- simulate_influence(
  n_nodes = 30, n_waves = 2, gamma = 0.4, beta = 0.3,
  normalize = "row", seed = 20260101L
)
# A COVARIATE IS ADDED, because most examples want one. simulate_influence()
# generates the outcome and the network; `x` is a node attribute with no role
# in that process, which is exactly what an example needs to show
# `exposure(x, via = tie)` -- exposure to an alter ATTRIBUTE rather than to the
# outcome itself. Its independence is the point: an example that used the
# outcome for both would confound the illustration with a real endogeneity.
set.seed(20260101L)
inf_nodes <- netis_nodes(sim$data)
inf_nodes$x <- stats::rnorm(nrow(inf_nodes))
demo_influence <- netis_data(inf_nodes, netis_ties(sim$data), wave_col = "wave")
attr(demo_influence, "truth") <- sim$truth

# ---------------------------------------------------------------------------
# demo_influence_groups -- four networks, two waves
#
# What a multi-group Influence fit needs: several independent networks, so a
# group-level random effect has something to vary over and a clustered variance
# has more than one cluster. Group sizes are UNEQUAL on purpose -- with equal
# sizes the three ICC(2) n_j conventions coincide, and a balanced example
# cannot show a reader the difference the choice makes.
# ---------------------------------------------------------------------------
set.seed(20260102L)
group_sizes <- c(a = 12L, b = 9L, c = 14L, d = 7L)
groups <- names(group_sizes)

nodes <- do.call(rbind, lapply(groups, function(g) {
  ids <- sprintf("%s%02d", g, seq_len(group_sizes[[g]]))
  n <- length(ids)
  # A group-level offset, so between-group variance is genuinely present and
  # an ICC computed on this data is not near zero by construction.
  offset <- stats::rnorm(1, sd = 0.8)
  x1 <- stats::rnorm(n)
  y1 <- offset + stats::rnorm(n)
  data.frame(
    group = g, node = rep(ids, 2), wave = rep(1:2, each = n),
    y = c(y1, offset + 0.4 * y1 + stats::rnorm(n, sd = 0.6)),
    x = c(x1, x1 + stats::rnorm(n, sd = 0.3)),
    stringsAsFactors = FALSE
  )
}))

ties <- do.call(rbind, lapply(groups, function(g) {
  ids <- sprintf("%s%02d", g, seq_len(group_sizes[[g]]))
  n <- length(ids)
  # A ring plus a few chords: connected, sparse, and not so regular that every
  # actor has identical centrality.
  from <- c(ids, ids[c(seq(3, n, by = 3), 1)])
  to <- c(ids[c(2:n, 1)], ids[c(seq(1, n - 2, by = 3), 2)])
  e <- data.frame(group = g, source = from, target = to, wave = 1L, tie = 1,
                  stringsAsFactors = FALSE)
  # No self-ties, and no repeated ordered pair: the chords can land on an edge
  # the ring already has, and rnetis refuses a tie table with two rows for one
  # (group, source, target, wave) rather than silently taking one of them.
  e <- e[e$source != e$target, ]
  e[!duplicated(e[c("source", "target")]), ]
}))

demo_influence_groups <- netis_data(nodes, ties, wave_col = "wave")

# ---------------------------------------------------------------------------
# demo_selection -- one network, two waves, a tie outcome
#
# For fit_selection(): a binary relation observed at two occasions, with a
# nodal covariate so sender() and receiver() have something to take, and
# enough persistence that prior_tie() is not estimating noise.
#
# The tie process is written out rather than simulated through a fitted model:
# a probability that rises with the sender's and receiver's tenure and with
# whether the tie existed before. Knowing it is what lets an example check that
# the fit recovers the sign.
# ---------------------------------------------------------------------------
set.seed(20260103L)
n_actors <- 20L
ids <- sprintf("p%02d", seq_len(n_actors))
tenure <- stats::rnorm(n_actors)
names(tenure) <- ids

pairs <- expand.grid(source = ids, target = ids, stringsAsFactors = FALSE)
pairs <- pairs[pairs$source != pairs$target, ]
row.names(pairs) <- NULL

# Wave 1: sender and receiver tenure raise the odds.
eta1 <- -1.4 + 0.5 * tenure[pairs$source] + 0.3 * tenure[pairs$target]
tie1 <- stats::rbinom(nrow(pairs), 1L, stats::pnorm(eta1))

# Wave 2: the same, plus strong persistence.
eta2 <- -1.4 + 0.5 * tenure[pairs$source] + 0.3 * tenure[pairs$target] +
  1.6 * tie1
tie2 <- stats::rbinom(nrow(pairs), 1L, stats::pnorm(eta2))

demo_selection <- netis_data(
  node_data = data.frame(group = 1L, node = ids, tenure = unname(tenure),
                     stringsAsFactors = FALSE),
  tie_data = rbind(
    data.frame(group = 1L, pairs, wave = 1L, tie = tie1, stringsAsFactors = FALSE),
    data.frame(group = 1L, pairs, wave = 2L, tie = tie2, stringsAsFactors = FALSE)
  ),
  wave_col = "wave",
  # DECLARED, because rnetis refuses to infer it. A zero here is a measured
  # non-tie: every ordered pair has a row at every wave, so an absent tie is
  # an observation and not a gap.
  tie_meta = list(tie = list(zero_meaning = "measured_zero"))
)
attr(demo_selection, "truth") <- list(
  intercept = -1.4, snd_tenure = 0.5, rcv_tenure = 0.3, prior_tie = 1.6
)

# ---------------------------------------------------------------------------
usethis::use_data(demo_influence, demo_influence_groups, demo_selection,
                  overwrite = TRUE, compress = "xz")
